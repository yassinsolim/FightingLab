"""FLClip1 encoding/decoding (must match ReplicatedStorage.FightingLab.Client.Motion.ClipLibrary).

Values are quantised to 12 bits per channel (2 base64 digits). Channel ranges: root position and limb positions
[-2, 2], rotations/poles [-1, 1], contacts/ground [0, 1]. Constant channels are stored once ("c" in the layout).
"""
from __future__ import annotations

import numpy as np

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
DIGIT = {c: i for i, c in enumerate(ALPHABET)}
LEVELS = 4095
N_CHANNELS = 58


def channel_range(c: int) -> tuple[float, float]:
    """c is 1-based (as in Luau)."""
    if c <= 3:
        return -2.0, 2.0
    if c <= 15:
        return -1.0, 1.0
    if c >= 56:
        return 0.0, 1.0
    k = (c - 16) % 10
    return (-2.0, 2.0) if k < 3 else (-1.0, 1.0)


def quantise(v: np.ndarray, lo: float, hi: float) -> np.ndarray:
    return np.clip(np.round((v - lo) / (hi - lo) * LEVELS), 0, LEVELS).astype(int)


def encode(channels: np.ndarray, const_eps: float = 0.0005) -> tuple[str, str, int]:
    """channels: (58, N). Returns (layout, data, clipped count)."""
    if channels.shape[0] != N_CHANNELS:
        raise ValueError("expected 58 channels")
    layout = []
    parts = []
    clipped = 0
    for c in range(N_CHANNELS):
        lo, hi = channel_range(c + 1)
        v = channels[c]
        clipped += int(np.sum((v < lo - 1e-9) | (v > hi + 1e-9)))
        q = quantise(v, lo, hi)
        if q.max() - q.min() <= max(0, int(const_eps / (hi - lo) * LEVELS)):
            layout.append("c")
            vals = [int(round(float(np.median(q))))]
        else:
            layout.append("v")
            vals = q.tolist()
        parts.append("".join(ALPHABET[x >> 6] + ALPHABET[x & 63] for x in vals))
    return "".join(layout), "".join(parts), clipped


def decode(layout: str, data: str, frames: int) -> np.ndarray:
    out = np.zeros((N_CHANNELS, frames))
    pos = 0
    for c in range(N_CHANNELS):
        lo, hi = channel_range(c + 1)
        step = (hi - lo) / LEVELS
        if layout[c] == "c":
            q = DIGIT[data[pos]] * 64 + DIGIT[data[pos + 1]]
            pos += 2
            out[c] = lo + q * step
        else:
            for f in range(frames):
                q = DIGIT[data[pos]] * 64 + DIGIT[data[pos + 1]]
                pos += 2
                out[c, f] = lo + q * step
    if pos != len(data):
        raise ValueError(f"data length {len(data)} != expected {pos}")
    return out


def clip_fields(name: str, channels: np.ndarray, meta: dict, source: str, ids: list[str], indent: str = "\t") -> tuple[str, int]:
    """Lua table body (fields only, one per line) for one FLClip1 clip."""
    layout, data, clipped = encode(channels)
    frames = channels.shape[1]
    fields = [
        'format = "FLClip1"', f'name = "{name}"', f"fps = {meta['fps']:g}", f"frames = {frames}",
        f"loop = {'true' if meta.get('loop') else 'false'}", f"speed = {meta.get('speed', 0.0):.4f}",
        "travel = { %.4f, %.4f, %.4f }" % tuple(meta.get("travel", [0, 0, 0])),
    ]
    for key in ("contact", "recover"):
        if meta.get(key) is not None:
            fields.append(f"{key} = {meta[key]:.4f}")
    if meta.get("fighter"):
        fields.append(f'fighter = "{meta["fighter"]}"')
    if meta.get("move"):
        fields.append(f'move = "{meta["move"]}"')
    if meta.get("stringIndex") is not None:
        fields.append(f"stringIndex = {int(meta['stringIndex'])}")
    if meta.get("mirrorAtRuntime"):
        fields.append("mirror = true")
    tags = meta.get("tags") or {}
    if tags:
        items = ", ".join(f'{k} = "{v}"' if isinstance(v, str) else f"{k} = {str(v).lower() if isinstance(v, bool) else v}" for k, v in sorted(tags.items()))
        fields.append("tags = { " + items + " }")
    fields.append("sources = { " + ", ".join(f'"{s}"' for s in ids) + " }")
    fields.append(f'source = "{source}"')
    fields.append(f'layout = "{layout}"')
    fields.append(f'data = "{data}"')
    return "".join(f"{indent}{f},\n" for f in fields), clipped


def header(name: str, ids: list[str], source: str, license_text: str, notes: str = "") -> str:
    if not ids:
        raise ValueError(f"clip {name} has no source ids (credits require catalog ids)")
    lines = [
        "-- sources: " + ", ".join(ids),
        f"-- {name}: generated by OV6/tools/mocap/convert.py. Do not edit by hand.",
        f"-- Source: {source}",
        f"-- License: {license_text}",
    ]
    if notes:
        lines.append(f"-- {notes}")
    return "\n".join(lines) + "\n"


def luau_module(name: str, channels: np.ndarray, meta: dict, source: str, license_text: str, notes: str = "",
                sources: list[str] | None = None) -> tuple[str, int]:
    """Clip module text. Line 1 is the machine-readable credit header `-- sources: <catalog ids>` (the integrator builds
    the in-game credits from it); the same ids are in the returned table's `sources` field."""
    ids = [s for s in (sources or []) if s]
    body, clipped = clip_fields(name, channels, meta, source, ids)
    return header(name, ids, source, license_text, notes) + "return {\n" + body + "}\n", clipped


GRIP_ROLES = ("Attacker", "Defender")
GRIP_LIMBS = ("LeftHand", "RightHand", "LeftFoot", "RightFoot")
R15_PARTS = ("Head", "UpperTorso", "LowerTorso", "LeftUpperArm", "LeftLowerArm", "LeftHand", "RightUpperArm",
             "RightLowerArm", "RightHand", "LeftUpperLeg", "LeftLowerLeg", "LeftFoot", "RightUpperLeg", "RightLowerLeg",
             "RightFoot")
# Named grip points on the PARTNER's body (its own left/right): R15 part + point in the part's box, each axis -1..1 of
# the half size (x right, y up, z back: -z is the part's front). Mirrors ClipLibrary.GRIP_ANCHORS (runtime).
GRIP_ANCHORS = {
    "Collar": ("UpperTorso", (0.0, 0.75, -1.2)), "Chest": ("UpperTorso", (0.0, 0.1, -1.2)),
    "Back": ("UpperTorso", (0.0, 0.1, 1.2)), "Nape": ("Head", (0.0, -0.75, 1.0)),
    "Belly": ("LowerTorso", (0.0, 0.5, -1.2)), "LowBack": ("LowerTorso", (0.0, 0.5, 1.2)),
    "LeftHip": ("LowerTorso", (-1.1, 0.0, 0.0)), "RightHip": ("LowerTorso", (1.1, 0.0, 0.0)),
    "LeftShoulder": ("LeftUpperArm", (0.0, 0.8, 0.0)), "RightShoulder": ("RightUpperArm", (0.0, 0.8, 0.0)),
    "LeftElbow": ("LeftLowerArm", (0.0, 0.9, 0.0)), "RightElbow": ("RightLowerArm", (0.0, 0.9, 0.0)),
    "LeftWrist": ("LeftLowerArm", (0.0, -0.9, 0.0)), "RightWrist": ("RightLowerArm", (0.0, -0.9, 0.0)),
    "LeftThigh": ("LeftUpperLeg", (0.0, 0.0, -1.1)), "RightThigh": ("RightUpperLeg", (0.0, 0.0, -1.1)),
    "LeftKnee": ("LeftLowerLeg", (0.0, 0.9, -1.0)), "RightKnee": ("RightLowerLeg", (0.0, 0.9, -1.0)),
    "LeftAnkle": ("LeftLowerLeg", (0.0, -0.9, 0.0)), "RightAnkle": ("RightLowerLeg", (0.0, -0.9, 0.0)),
}


def check_grip(g: dict, duration: float | None = None) -> list[str]:
    """Problems of one FLThrow1 grip entry (empty list = valid)."""
    out = []
    if g.get("role") not in GRIP_ROLES:
        out.append(f"grip role {g.get('role')!r} (use {GRIP_ROLES})")
    if g.get("limb") not in GRIP_LIMBS:
        out.append(f"grip limb {g.get('limb')!r} (use {GRIP_LIMBS})")
    if g.get("anchor") is not None and g["anchor"] not in GRIP_ANCHORS:
        out.append(f"grip anchor {g['anchor']!r} (use {sorted(GRIP_ANCHORS)})")
    if g.get("anchor") is None and g.get("part") not in R15_PARTS:
        out.append(f"grip needs anchor or a valid R15 part, got part {g.get('part')!r}")
    at = g.get("at")
    if at is not None and (len(at) != 3 or not all(isinstance(x, (int, float)) and abs(x) <= 3 for x in at)):
        out.append(f"grip at {at!r} must be 3 numbers within -3..3 (part half-sizes)")
    try:
        t0, t1 = float(g["from"]), float(g["to"])
        if t1 < t0:
            out.append(f"grip to {t1} < from {t0}")
        if duration is not None and (t0 < -1e-6 or t1 > duration + 1e-6):
            out.append(f"grip window {t0}..{t1} outside the clip (0..{duration:.3f} s)")
    except (KeyError, TypeError, ValueError):
        out.append("grip needs numeric from/to (seconds of clip time)")
    for key in ("fade", "weight"):
        if g.get(key) is not None and not (isinstance(g[key], (int, float)) and 0 <= g[key] <= (1 if key == "weight" else 1.0)):
            out.append(f"grip {key} {g[key]!r} out of range")
    return out


def mirror_grip(g: dict) -> dict:
    """Left/right swap of a grip (limb, partner anchor/part, x of the point) for a mirrored throw."""
    def swap(s):
        if not isinstance(s, str):
            return s
        if s.startswith("Left"):
            return "Right" + s[4:]
        if s.startswith("Right"):
            return "Left" + s[5:]
        return s
    out = dict(g)
    for key in ("limb", "anchor", "part"):
        if out.get(key) is not None:
            out[key] = swap(out[key])
    if out.get("at") is not None:
        out["at"] = [-float(out["at"][0]), float(out["at"][1]), float(out["at"][2])]
    return out


def grip_fields(grips: list[dict], duration: float | None = None) -> str:
    """Lua `grips = { ... }` field of an FLThrow1 module (validated)."""
    lines = []
    for i, g in enumerate(grips):
        problems = check_grip(g, duration)
        if problems:
            raise ValueError(f"grip {i}: " + "; ".join(problems))
        items = [f'role = "{g["role"]}"', f'limb = "{g["limb"]}"']
        if g.get("anchor") is not None:
            items.append(f'anchor = "{g["anchor"]}"')
        if g.get("part") is not None:
            items.append(f'part = "{g["part"]}"')
        if g.get("at") is not None:
            items.append("at = { %.3f, %.3f, %.3f }" % tuple(float(x) for x in g["at"]))
        items.append(f"from = {float(g['from']):.4f}")
        items.append(f"to = {float(g['to']):.4f}")
        for key in ("fade", "weight"):
            if g.get(key) is not None:
                items.append(f"{key} = {float(g[key]):.4f}")
        lines.append("\t\t{ " + ", ".join(items) + " },\n")
    return "\tgrips = {\n" + "".join(lines) + "\t},\n"


def throw_module(name: str, attacker: tuple[np.ndarray, dict], defender: tuple[np.ndarray, dict], meta: dict,
                 source: str, license_text: str, notes: str = "", sources: list[str] | None = None,
                 break_attacker: tuple[np.ndarray, dict] | None = None,
                 break_defender: tuple[np.ndarray, dict] | None = None) -> tuple[str, int]:
    """FLThrow1 module: two synchronised FLClip1 tracks (attacker, defender) + impact/distance, and optionally the
    break tracks played when the throw is broken (throw.broken: from throw.breakFrame over ThrowBreakFrames) and
    `meta["grips"]` (hands/feet held on the partner's real body point at runtime; see grip_fields)."""
    ids = [s for s in (sources or []) if s]
    a_body, ca = clip_fields(name + ".attacker", attacker[0], attacker[1], source, ids, "\t\t")
    d_body, cd = clip_fields(name + ".defender", defender[0], defender[1], source, ids, "\t\t")
    fields = ['format = "FLThrow1"', f'name = "{name}"']
    if meta.get("fighter"):
        fields.append(f'fighter = "{meta["fighter"]}"')
    fields.append(f'move = "{meta["move"]}"')
    fields.append(f"impact = {float(meta['impact']):.4f}")
    fields.append(f"distance = {float(meta['distance']):.4f}")
    fields.append("sources = { " + ", ".join(f'"{s}"' for s in ids) + " }")
    text = header(name, ids, source, license_text, notes) + "return {\n" + "".join(f"\t{f},\n" for f in fields)
    text += "\tattacker = {\n" + a_body + "\t},\n\tdefender = {\n" + d_body + "\t},\n"
    clipped = ca + cd
    for key, track in (("breakAttacker", break_attacker), ("breakDefender", break_defender)):
        if track is not None:
            body, c = clip_fields(f"{name}.{key}", track[0], track[1], source, ids, "\t\t")
            text += f"\t{key} = {{\n" + body + "\t},\n"
            clipped += c
    if meta.get("grips"):
        duration = (attacker[0].shape[1] - 1) / float(attacker[1]["fps"])
        text += grip_fields(meta["grips"], duration)
    text += cinematic_fields(meta)
    text += "}\n"
    return text, clipped


def _lua_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return f"{float(v):.4f}".rstrip("0").rstrip(".") if float(v) != int(float(v)) else str(int(float(v)))
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, (list, tuple)):
        return "{ " + ", ".join(_lua_value(x) for x in v) + " }"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {_lua_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(f"cannot write {v!r} to Luau")


def cinematic_fields(meta: dict) -> str:
    """Round-6 Ultimate cinematic fields of an FLThrow1 (Motion.Cinematic): impacts (normalised times), hits (striking limb
    per impact), camera keys (t, pos, look, fov, cut, ease, roll; studs in the attacker's frame), release, endKind."""
    out = ""
    if meta.get("impacts"):
        out += "\timpacts = " + _lua_value([round(float(u), 4) for u in meta["impacts"]]) + ",\n"
    if meta.get("hits"):
        out += "\thits = {\n" + "".join("\t\t" + _lua_value(h) + ",\n" for h in meta["hits"]) + "\t},\n"
    if meta.get("camera"):
        rows = []
        for k in meta["camera"]:
            row = {"t": round(float(k["t"]), 4), "pos": [round(float(x), 3) for x in k["pos"]], "look": [round(float(x), 3) for x in k["look"]]}
            for opt in ("fov", "cut", "ease", "roll"):
                if opt in k and k[opt] is not None:
                    row[opt] = k[opt]
            rows.append(row)
        out += "\tcamera = {\n" + "".join("\t\t" + _lua_value(r) + ",\n" for r in rows) + "\t},\n"
    if meta.get("release") is not None:
        out += f"\trelease = {float(meta['release']):.4f},\n"
    if meta.get("endKind"):
        out += f'\tendKind = "{meta["endKind"]}",\n'
    return out


# Reading clip modules back (offline verification) ------------------------------------------------------------------

def parse_lua_table(text: str):
    """Parses the `return { ... }` literal of a generated clip module (strings, numbers, booleans, nested tables;
    keyed fields and positional items). Comments are skipped."""
    i = text.index("return")
    s = text[i + 6:]
    pos = 0

    def skip():
        nonlocal pos
        while pos < len(s):
            if s[pos].isspace():
                pos += 1
            elif s.startswith("--", pos):
                nl = s.find("\n", pos)
                pos = len(s) if nl < 0 else nl + 1
            else:
                break

    def value():
        nonlocal pos
        skip()
        ch = s[pos]
        if ch == "{":
            pos += 1
            out_map, out_list = {}, []
            while True:
                skip()
                if s[pos] == "}":
                    pos += 1
                    break
                # key = value ?
                j = pos
                while j < len(s) and (s[j].isalnum() or s[j] == "_"):
                    j += 1
                k = j
                while k < len(s) and s[k].isspace():
                    k += 1
                if j > pos and k < len(s) and s[k] == "=" and s[k + 1] != "=":
                    key = s[pos:j]
                    pos = k + 1
                    out_map[key] = value()
                else:
                    out_list.append(value())
                skip()
                if s[pos] in ",;":
                    pos += 1
            if out_map and out_list:
                out_map["__list"] = out_list
                return out_map
            return out_map if out_map else out_list
        if ch == '"':
            end = s.index('"', pos + 1)
            v = s[pos + 1:end]
            pos = end + 1
            return v
        j = pos
        while j < len(s) and (s[j].isalnum() or s[j] in "+-._"):
            j += 1
        tok = s[pos:j]
        pos = j
        if tok == "true":
            return True
        if tok == "false":
            return False
        if tok == "nil":
            return None
        return float(tok) if any(c in tok for c in ".eE") else int(tok)

    return value()


def clip_channels(raw: dict) -> np.ndarray:
    return decode(raw["layout"], raw["data"], int(raw["frames"]))