"""Generate CREDITS.md for FightingLab from the fighter specs (sourceAssets) plus optional external credits.

  python gen_credits.py --specs <dir with <Id>.json> --out <CREDITS.md> [--external <credits-external.json>]
                        [--luau-out <ReplicatedStorage.FightingLab.Credits.luau>]

Each spec's "sourceAssets" entries ({id, name, creator, kind}) are listed per fighter and in one combined,
de-duplicated table. credits-external.json (optional) is a list of
{ "title", "author", "url", "license", "licenseUrl", "credit", "usedFor" } for models or files from outside Roblox.
--luau-out also writes the same data as a ModuleScript for the in-game credits screen. In-game text is reduced
to printable ASCII because decorative catalog glyphs render as "?"; CREDITS.md keeps the exact published names.
"""
import argparse
import json
import os
import re
import unicodedata

ORDER = ["Kael", "Sierra", "Goran", "Lumi", "Rhys", "Nia"]
INTRO = ("FightingLab's fighters, names, moves, stages and code are original. The fighters are assembled from the "
         "Roblox avatar marketplace items below; thank you to their creators.")


def clean_kind(kind):
    # Spec kinds sometimes carry build notes in parentheses ("... (swapped for approved texture)"); credits show the type only.
    return re.sub(r"\s*\([^)]*\)", "", str(kind or "")).strip()


# Look-alike letters (Cyrillic/Greek) and typographic punctuation that catalog names use in place of ASCII.
LOOKALIKES = str.maketrans({
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O", "Р": "P", "С": "C", "Т": "T", "Х": "X",
    "У": "Y", "І": "I", "Ј": "J", "Ѕ": "S", "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
    "і": "i", "ј": "j", "ѕ": "s", "Α": "A", "Β": "B", "Ε": "E", "Ζ": "Z", "Η": "H", "Ι": "I", "Κ": "K", "Μ": "M",
    "Ν": "N", "Ο": "O", "Ρ": "P", "Τ": "T", "Υ": "Y", "Χ": "X", "ο": "o", "ν": "v",
    "‘": "'", "’": "'", "‛": "'", "`": "'", "“": '"', "”": '"', "„": '"', "–": "-", "—": "-", "…": "...",
    "\u00a0": " ",
})


def ascii_clean(text):
    text = unicodedata.normalize("NFKD", str(text).translate(LOOKALIKES))
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    out = "".join(ch if 32 <= ord(ch) < 127 else " " for ch in text)
    return " ".join(out.split()).strip(" -_|/") or "?"


def lua_str(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n") + '"'


def write_luau(path, fighters, external, world=None):
    out = ["-- Generated by tools/gen_credits.py from the fighter specs. Do not edit by hand.",
           "return {", f"\tintro = {lua_str(INTRO)},", "\tfighters = {"]
    for fighter in fighters:
        out.append(f"\t\t{{ name = {lua_str(ascii_clean(fighter['name']))}, items = {{")
        for entry in fighter["items"]:
            try:
                asset_id = int(entry.get("id"))
            except (TypeError, ValueError):
                asset_id = 0
            out.append(f"\t\t\t{{ name = {lua_str(ascii_clean(entry.get('name', '?')))}, "
                       f"creator = {lua_str(ascii_clean(entry.get('creator', '?')))}, "
                       f"kind = {lua_str(ascii_clean(clean_kind(entry.get('kind', ''))))}, id = {asset_id} }},")
        out.append("\t\t} },")
    out.append("\t},")
    out.append("\texternal = {")
    for e in external:
        out.append(f"\t\t{{ credit = {lua_str(ascii_clean(e.get('credit') or e.get('title') or '?'))}, "
                   f"license = {lua_str(ascii_clean(e.get('license', '?')))}, "
                   f"usedFor = {lua_str(ascii_clean(e.get('usedFor', '?')))} }},")
    out.append("\t},")
    # Creator Store assets used by the lobby and arenas (rendered as their own section on the credits screen).
    out.append("\tworld = {")
    for w in world or []:
        try:
            asset_id = int(w.get("assetId"))
        except (TypeError, ValueError):
            asset_id = 0
        out.append(f"\t\t{{ name = {lua_str(ascii_clean(w.get('name', '?')))}, "
                   f"creator = {lua_str(ascii_clean(w.get('creator', '?')))}, "
                   f"kind = {lua_str(ascii_clean(w.get('kind', '')))}, "
                   f"usedFor = {lua_str(ascii_clean(w.get('usedFor', '')))}, id = {asset_id} }},")
    out += ["\t},", "}", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))


def catalog_url(entry):
    kind = (entry.get("kind") or "").lower()
    if "bundle" in kind:
        return f"https://www.roblox.com/bundles/{entry['id']}"
    if "generated" in kind:
        return ""
    return f"https://www.roblox.com/catalog/{entry['id']}"


def used_clip_sources(dirs):
    """Source ids named on '-- sources:' header lines of exported clip modules (*.Motion.Clips.*.luau)."""
    used = set()
    for d in dirs:
        if not os.path.isdir(d):
            continue
        for fn in os.listdir(d):
            if ".Motion.Clips." not in fn or not fn.endswith(".luau"):
                continue
            with open(os.path.join(d, fn), encoding="utf-8-sig") as fh:
                for line in fh:
                    if line.startswith("-- sources:"):
                        used.update(s for s in re.split(r"[\s,]+", line[len("-- sources:"):]) if s)
    return used


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--specs", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--external")
    ap.add_argument("--world-assets")
    ap.add_argument("--luau-out")
    # Clip export folders: external entries with a "sourcePrefix" are kept only if a shipped clip names such a source.
    ap.add_argument("--clip-src", action="append", default=[])
    a = ap.parse_args()

    lines = ["# FightingLab credits", "", INTRO, ""]
    combined = {}
    fighters = []
    for fid in ORDER:
        path = os.path.join(a.specs, fid + ".json")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8-sig") as fh:
            spec = json.load(fh)
        fighters.append({"name": spec.get("displayName", fid), "items": spec.get("sourceAssets", [])})
        lines.append(f"## {spec.get('displayName', fid)}")
        lines.append("")
        lines.append("| Item | Creator | Type | Link |")
        lines.append("|---|---|---|---|")
        for entry in spec.get("sourceAssets", []):
            name = str(entry.get("name", "?")).replace("|", "/")
            creator = str(entry.get("creator", "?")).replace("|", "/")
            kind = clean_kind(entry.get("kind", "")).replace("|", "/")
            url = catalog_url(entry)
            lines.append(f"| {name} | {creator} | {kind} | {url} |")
            key = str(entry.get("id"))
            combined.setdefault(key, {"name": name, "creator": creator, "kind": kind, "url": url, "fighters": []})
            combined[key]["fighters"].append(spec.get("displayName", fid))
        lines.append("")

    external = []
    if a.external and os.path.exists(a.external):
        with open(a.external, encoding="utf-8-sig") as fh:
            external = json.load(fh)
        if a.clip_src:
            used = used_clip_sources(a.clip_src)
            kept = []
            for e in external:
                prefix = e.get("sourcePrefix")
                hits = sorted(s for s in used if prefix and s.startswith(prefix))
                if prefix and not hits:
                    print(f"dropped external credit (no clip uses {prefix}*): {e.get('title')}")
                    continue
                if prefix:
                    print(f"external credit {e.get('title')}: {len(hits)} source ids used")
                kept.append(e)
            external = kept
        if external:
            lines += ["## Models and files from outside Roblox", ""]
            for e in external:
                lines.append(f"- {e.get('credit') or e.get('title')} ({e.get('license', '?')}"
                             f"{', ' + e['licenseUrl'] if e.get('licenseUrl') else ''}). Used for: {e.get('usedFor', '?')}.")
            lines.append("")

    world = []
    if a.world_assets and os.path.exists(a.world_assets):
        with open(a.world_assets, encoding="utf-8-sig") as fh:
            world = json.load(fh)
        # Accept a bare list or {"assets": [...]}, and "assetId" or "id" per entry.
        if isinstance(world, dict):
            world = world.get("assets", [])
        for w in world:
            if w.get("assetId") is None and w.get("id") is not None:
                w["assetId"] = w["id"]
        if world:
            lines += ["## Lobby and arenas", "", "| Asset | Creator | Type | Used for | Link |", "|---|---|---|---|---|"]
            for w in world:
                asset_id = w.get("assetId")
                link = f"https://create.roblox.com/store/asset/{asset_id}" if asset_id else ""
                cells = [str(w.get(k, "?")).replace("|", "/") for k in ("name", "creator", "kind", "usedFor")]
                lines.append(f"| {cells[0]} | {cells[1]} | {cells[2]} | {cells[3]} | {link} |")
            lines.append("")

    lines += ["## All marketplace items", "", "| Item | Creator | Used by | Link |", "|---|---|---|---|"]
    for key, c in sorted(combined.items(), key=lambda kv: (kv[1]["creator"].lower(), kv[1]["name"].lower())):
        lines.append(f"| {c['name']} | {c['creator']} | {', '.join(c['fighters'])} | {c['url']} |")
    lines.append("")
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {a.out}: {len(combined)} unique items")
    if a.luau_out:
        write_luau(a.luau_out, fighters, external, world)
        print(f"wrote {a.luau_out}")


if __name__ == "__main__":
    main()
